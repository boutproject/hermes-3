#!/usr/bin/env python3
"""Independent covariant skew-current reference for Reynolds convergence tests.

The reference differentiates c*(v.grad)grad(Phi) + grad(Phi)*div(c*v)/2
using Christoffel symbols of the perpendicular metric. It does not use the
Christoffel-free split/curl identity implemented by Hermes. --cpp emits BOUT
expression strings for the sheared annulus used by FakeMesh.
"""

import argparse
from functools import cache

import sympy as s

x, z = s.symbols("x z", real=True)


@cache
def reference(case="periodic"):
    r = s.Rational
    if case in ("annulus", "cpp"):
        g11, g13, g33 = s.Integer(1), -r(1, 4) / x, r(17, 16) / x**2
        J, c = x, x**2
        phi = s.sin(s.pi * (x - 1)) * s.cos(z)
        psi = r(1, 5) * s.sin(s.pi * (x - 1)) ** 2 * s.sin(2 * z)
    else:
        phase = x if case == "cpp" else x + z
        g11 = 1 + r(1, 10) * s.cos(x)
        g13 = r(1, 4) + r(1, 20) * s.sin(phase)
        D = 1 + r(1, 10) * s.sin(x)
        g33 = (D + g13**2) / g11
        J = 1 + r(1, 10) * s.cos(x)
        c = 1 + r(1, 5) * s.sin(x) + r(1, 10) * s.cos(z)
        phi = s.sin(x) * s.cos(z) + r(1, 10) * s.cos(2 * z)
        psi = r(1, 5) * s.cos(2 * x) * s.sin(z)
    H = s.Matrix([[g11, g13], [g13, g33]])
    D = g11 * g33 - g13**2
    G = s.Matrix([[g33, -g13], [-g13, g11]]) / D
    coordinates = (x, z)
    gradient = lambda f: s.Matrix([s.diff(f, q) for q in coordinates])
    divergence = lambda v: (
        sum(s.diff(J * v[i], q) for i, q in enumerate(coordinates)) / J
    )
    v = s.Matrix([s.diff(phi, z), -s.diff(phi, x)])
    u = H * gradient(phi + psi)
    Gamma = s.zeros(2, 1)
    for i in range(2):
        for j in range(2):
            Gamma[i] += c * v[j] * s.diff(u[i], coordinates[j])
            for k in range(2):
                christoffel = sum(
                    H[i, l]
                    * (
                        s.diff(G[l, k], coordinates[j])
                        + s.diff(G[l, j], coordinates[k])
                        - s.diff(G[j, k], coordinates[l])
                    )
                    / 2
                    for l in range(2)
                )
                Gamma[i] += c * v[j] * christoffel * u[k]
        Gamma[i] += u[i] * divergence(c * v) / 2
    omega = divergence(c * u)
    return {
        "phi": phi,
        "psi": psi,
        "c": c,
        "J": J,
        "g11": g11,
        "g13": g13,
        "g33": g33,
        "D": D,
        "omega": omega,
        "expected": divergence(Gamma),
        "expected_x": J * Gamma[0],
        "expected_z": J * Gamma[1],
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--cpp", action="store_true")
    args = parser.parse_args()
    from boutdata.mms import exprToStr

    if args.cpp:
        print("// Generated by generate_reynolds_reference.py --cpp; do not edit.")
        print("#pragma once\nnamespace reynolds_reference {")
    for name, expression in reference("cpp" if args.cpp else "periodic").items():
        if args.cpp:
            # C++ checks the divergence; Python also checks the current's gauge.
            if name in ("expected_x", "expected_z"):
                continue
            expression = expression.subs(x, s.Symbol("r", real=True))
            print(
                f'inline constexpr auto {name} = R"expr({exprToStr(expression)})expr";'
            )
        else:
            print(f"{name}: {exprToStr(expression)}")
    if args.cpp:
        print("} // namespace reynolds_reference")


if __name__ == "__main__":
    main()
