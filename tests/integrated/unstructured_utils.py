"""Helpers for the ``*-fci-unstructured`` tests.

Each unstructured test reuses the input file of its structured counterpart
(``../<name>-fci/data/BOUT.inp``) and writes ``data/BOUT.inp`` from it at
run time, so the two tests can never drift apart. Changes:

- The ``precomputed`` XZ interpolation required on unstructured grids is
  selected (``MXG = MYG = 1`` come from the grid file).
- On unstructured grids BOUT++'s index coordinates ``x`` and ``z`` are not
  geometric: nodes are stored along x and ``nz = 1``. Expressions using
  ``x`` or ``z`` are parsed with sympy and rewritten in terms of ``xu`` and
  ``zu``, which are defined from the grid coordinates ``R`` and ``Z`` via
  ``[input:grid_variables]``. Each rewritten expression is checked numerically
  against the original.
"""

import re
from pathlib import Path

import numpy as np
import sympy as sp
from boutdata.mms import exprToStr

_KEY_VALUE = re.compile(r"^(\s*)([^\s=#\[]+)(\s*=\s*)(.*?)(\s*(?:#.*)?)$")
_SECTION = re.compile(r"^\s*\[([^\]]+)\]")

X, Y, Z, T = sp.symbols("x y z t")
XU, ZU = sp.symbols("xu zu")


def _rewrite(value: str):
    """Return ``value`` rewritten in terms of xu, zu, or None if it does not
    use the symbols x or z (or is not a plain sympy-parsable expression)."""
    if not re.search(r"(?<![\w:`])[xz](?![\w:`])", value):
        return None
    try:
        expr = sp.sympify(
            value.replace("^", "**"), locals={"x": X, "y": Y, "z": Z, "t": T}
        )
    except (sp.SympifyError, SyntaxError, TypeError):
        return None
    if not expr.free_symbols & {X, Z}:
        return None
    new = exprToStr(expr.subs({X: XU, Z: ZU}, simultaneous=True))

    # Numerical check: the new string, read back with xu -> x, zu -> z,
    # must give the same values as the original.
    back = sp.sympify(new.replace("^", "**"), locals={"xu": X, "zu": Z, "y": Y, "t": T})
    rng = np.random.default_rng(0)
    f0 = sp.lambdify((X, Y, Z, T), expr, "numpy")
    f1 = sp.lambdify((X, Y, Z, T), back, "numpy")
    for _ in range(20):
        p = rng.uniform(0.0, 6.0, 4)
        a, b = float(f0(*p)), float(f1(*p))
        if not np.isclose(a, b, rtol=1e-12, atol=1e-14 * max(1.0, abs(a))):
            raise ValueError(f"Rewriting changed the expression: {value!r} -> {new!r}")
    return new


def make_unstructured_input(structured_test: str, xu: str, zu: str, here: Path):
    """Write ``here/data/BOUT.inp`` from ``../<structured_test>/data/BOUT.inp``.

    Parameters
    ----------
    structured_test : str
        Name of the structured test directory (sibling of ``here``)
    xu, zu : str
        BOUT++ expressions for BOUT's index coordinates ``x`` and ``z`` of the
        structured grid in terms of ``gridvar:R`` and ``gridvar:Z``
    here : Path
        Directory of the unstructured test
    """
    source = here.parent / structured_test / "data" / "BOUT.inp"
    lines = source.read_text().splitlines()
    if any(
        (m := _SECTION.match(line)) and m.group(1).strip().endswith("xzinterpolation")
        for line in lines
    ):
        raise ValueError(f"{source} already sets an XZ interpolation")

    out = []
    section = ""
    rewritten = []
    mesh_done = False
    for line in lines:
        m = _SECTION.match(line)
        if m:
            section = m.group(1).strip()
            out.append(line)
            if section == "mesh":
                # MXG = MYG = 1 are read from the grid file
                out += [
                    "",
                    "[mesh:paralleltransform:xzinterpolation]",
                    "type = precomputed",
                    "",
                    "[mesh]",
                ]
                mesh_done = True
            continue
        m = _KEY_VALUE.match(line)
        if m and not line.lstrip().startswith("#"):
            indent, key, eq, value, comment = m.groups()
            new = _rewrite(value)
            if new is not None:
                out.append(f"{indent}{key}{eq}{new}{comment}")
                rewritten.append(f"{section}:{key}")
                continue
        out.append(line)
    if not mesh_done:
        out += [
            "",
            "[mesh:paralleltransform:xzinterpolation]",
            "type = precomputed",
        ]

    header = [
        f"# Generated by unstructured_utils.py from ../{structured_test}/data/BOUT.inp",
        "# Do not edit: edit the structured input instead.",
        "",
    ]
    if rewritten:
        # Only defined when used: Hermes-3 stops on unused options
        header += [
            "# BOUT++ index coordinates of the structured grid, from the grid geometry",
            f"xu = {xu}",
            f"zu = {zu}",
            "",
        ]
        out += ["", "[input:grid_variables]", "R = field3d", "Z = field3d", ""]
    out = header + out

    data = here / "data"
    data.mkdir(exist_ok=True)
    (data / "BOUT.inp").write_text("\n".join(out))
    return rewritten
